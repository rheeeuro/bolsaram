-- 0015: 회원 로그인을 매직 링크로 — 전화번호 OTP 제거
--
-- SMS 를 쓰지 않기로 했다. 회원 로그인 경로가 전화번호 OTP 하나였고, 그 경로는
-- 발송 수단이 없어 실제로 동작할 수 없었다. 게다가 **회원 계정을 만드는 경로가
-- 시드밖에 없었다** — verifyLoginCode 는 기존 계정만 찾고 없으면 거부한다.
--
-- 주선자가 이미 카카오톡으로 초대 링크를 보내고 있다. 그 링크가 세션까지 만들면
-- 별도 발송 수단이 필요 없고, 링크를 소비할 때 회원 계정도 함께 만들 수 있다.
--
--   초대 링크 소비 → 프로필에 주인이 없으면 회원 계정 생성 + 연결 + 세션
--                 → 주인이 있으면 그 계정으로 세션 (재로그인)
--
-- 전화번호는 더 이상 신원이 아니다. 주선자가 기록해 두는 연락 수단일 뿐이므로
-- 회원에게 필수가 아니게 한다.

ALTER TABLE users DROP CONSTRAINT users_member_needs_phone;

