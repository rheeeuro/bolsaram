-- 0042: 채팅 시각을 밀리초 정밀도로 맞춘다
--
-- 채팅의 커서는 시각이다 — 폴링은 「마지막으로 받은 시각 이후」를 묻고, 읽음 표시는
-- 「여기까지 읽었다」를 그 시각으로 남긴다. 그런데 화면이 들고 있는 값은 JSON 을
-- 거친 ISO 문자열이라 **밀리초까지**이고, Postgres 의 `timestamptz` 는 마이크로초까지
-- 저장한다. `04:44:55.291168` 로 저장된 글을 `04:44:55.291` 로 읽었다고 표시하면
-- 그 글은 영원히 안 읽음으로 남는다 — 배지의 숫자가 1 에서 줄지 않는다(실측).
-- 폴링도 마지막 한 줄을 매번 다시 받는다.
--
-- 커서를 id 로 바꾸는 방법도 있지만, 「그 시각 이후」라는 질문 자체는 자연스럽고
-- 화면이 시각으로 정렬한다. 저장 정밀도를 화면이 표현할 수 있는 단위로 맞추는 쪽이
-- 단순하다. 밀리초는 운영 대화에 충분하다.

ALTER TABLE group_messages  ALTER COLUMN created_at   TYPE timestamptz(3);
ALTER TABLE group_chat_prefs ALTER COLUMN last_read_at TYPE timestamptz(3);
