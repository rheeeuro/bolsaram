/**
 * 통합 테스트가 자기 데이터를 표시하는 태그.
 *
 * 태그는 `afterAll` 이 `LIKE '<태그>%'` 로 **자기가 만든 것만** 지우는 데 쓰이므로
 * 파일마다 달라야 하고 실행마다 달라야 한다. 동시에 모임 이름에도 들어가는데 그
 * 칸은 `GROUP_NAME_MAX_LENGTH`(20자)까지라, 밀리초 전체를 붙이면 이름을 붙일 자리가
 * 남지 않는다. 파일을 가르는 접두사와 시각 뒷자리 7개만 남긴다 — 접두사가 파일을
 * 가르고 뒷자리가 실행을 가른다.
 */
export function runTag(prefix: string): string {
  return `${prefix}${Date.now() % 10_000_000}`;
}
